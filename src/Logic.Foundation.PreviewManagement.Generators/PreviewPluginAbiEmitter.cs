    private static void EmitReadProperty(StringBuilder builder, PropertyModel property)
    {
        string local = "value_" + property.Name;
        switch (property.Kind)
        {
            case WireKind.Bool:
                builder.AppendLine($"        bool {local} = ReadBool(data, ref offset);");
                break;
            case WireKind.UInt8:
                Assign(builder, property, local, "ReadUInt8(data, ref offset)");
                break;
            case WireKind.Int8:
                Assign(builder, property, local, "(sbyte)ReadUInt8(data, ref offset)");
                break;
            case WireKind.Int16:
                Assign(builder, property, local, "ReadInt16(data, ref offset)");
                break;
            case WireKind.UInt16:
                Assign(builder, property, local, "ReadUInt16(data, ref offset)");
                break;
            case WireKind.Int32:
                Assign(builder, property, local, "ReadInt32(data, ref offset)");
                break;
            case WireKind.UInt32:
                Assign(builder, property, local, "ReadUInt32(data, ref offset)");
                break;
            case WireKind.Int64:
                Assign(builder, property, local, "ReadInt64(data, ref offset)");
                break;
            case WireKind.UInt64:
                Assign(builder, property, local, "ReadUInt64(data, ref offset)");
                break;
            case WireKind.Char:
                builder.AppendLine($"        char {local} = (char)ReadUInt16(data, ref offset);");
                break;
            case WireKind.String:
                builder.AppendLine($"        string {local} = ReadString(data, ref offset) ?? string.Empty;");
                break;
            case WireKind.Single:
                builder.AppendLine($"        float {local} = global::System.BitConverter.Int32BitsToSingle(ReadInt32(data, ref offset));");
                break;
            case WireKind.Double:
                builder.AppendLine($"        double {local} = global::System.BitConverter.Int64BitsToDouble(ReadInt64(data, ref offset));");
