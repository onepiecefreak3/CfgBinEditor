            case WireKind.Rgba32:
                builder.AppendLine($"        byte {local}_R = ReadUInt8(data, ref offset);");
                builder.AppendLine($"        byte {local}_G = ReadUInt8(data, ref offset);");
                builder.AppendLine($"        byte {local}_B = ReadUInt8(data, ref offset);");
                builder.AppendLine($"        byte {local}_A = ReadUInt8(data, ref offset);");
                builder.AppendLine($"        {property.QualifiedType} {local} = new {property.QualifiedType}({local}_R, {local}_G, {local}_B, {local}_A);");
                break;
        }
    }

    private static void Assign(StringBuilder builder, PropertyModel property, string local, string expression)
    {
        if (property.IsEnum)
            builder.AppendLine($"        {property.QualifiedType} {local} = ({property.QualifiedType}){expression};");
        else if (property.Kind == WireKind.UInt16 && property.QualifiedType.EndsWith("System.Char", StringComparison.Ordinal))
            builder.AppendLine($"        char {local} = (char){expression};");
        else
            builder.AppendLine($"        {RawType(property.Kind)} {local} = {expression};");
    }

    private static string RawType(WireKind kind)
    {
        return kind switch
        {
            WireKind.Bool => "bool",
            WireKind.UInt8 => "byte",
            WireKind.Int8 => "sbyte",
            WireKind.Int16 => "short",
            WireKind.UInt16 => "ushort",
            WireKind.Int32 => "int",
            WireKind.UInt32 => "uint",
            WireKind.Int64 => "long",
            WireKind.UInt64 => "ulong",
            WireKind.Char => "char",
            WireKind.String => "string",
            WireKind.Single => "float",
            WireKind.Double => "double",
            _ => "byte"
        };
    }

