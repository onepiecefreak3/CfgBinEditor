        builder.AppendLine("    {");
        builder.AppendLine("        if (!first)");
        builder.AppendLine("            json.Append(',');");
        builder.AppendLine("        json.Append('\"').Append(name).Append('\"').Append(':');");
        builder.AppendLine("        AppendString(json, value);");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private static void AppendField(StringBuilder json, string name, string[]? values)");
        builder.AppendLine("    {");
        builder.AppendLine("        json.Append(',').Append('\"').Append(name).Append('\"').Append(':').Append('[');");
        builder.AppendLine("        if (values is not null)");
        builder.AppendLine("        {");
        builder.AppendLine("            for (int index = 0; index < values.Length; index++)");
        builder.AppendLine("            {");
        builder.AppendLine("                if (index > 0)");
        builder.AppendLine("                    json.Append(',');");
        builder.AppendLine("                AppendString(json, values[index]);");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        json.Append(']');");
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    private static void AppendString(StringBuilder json, string? value)");
        builder.AppendLine("    {");
        builder.AppendLine("        if (value is null)");
        builder.AppendLine("        {");
        builder.AppendLine("            json.Append(\"null\");");
        builder.AppendLine("            return;");
        builder.AppendLine("        }");
        builder.AppendLine();
        builder.AppendLine("        json.Append('\"');");
        builder.AppendLine("        foreach (char character in value)");
        builder.AppendLine("        {");
        builder.AppendLine("            switch (character)");
        builder.AppendLine("            {");
        builder.AppendLine("""
                case '\\': json.Append("\\\\"); break;
                case '"': json.Append("\\\""); break;
                case '\n': json.Append("\\n"); break;
                case '\r': json.Append("\\r"); break;
                case '\t': json.Append("\\t"); break;
                default:
                    if (character < 0x20)
                        json.Append("\\u").Append(((int)character).ToString("x4"));
                    else
                        json.Append(character);
                    break;
""");
        builder.AppendLine("            }");
        builder.AppendLine("        }");
        builder.AppendLine("        json.Append('\"');");
        builder.AppendLine("    }");
    }

    private static void AppendWrite(StringBuilder builder, string name, string parameter, string body)
    {
        builder.AppendLine($"    private static void {name}(global::System.Collections.Generic.List<byte> buffer, {parameter})");
        builder.AppendLine("    {");
        builder.AppendLine($"        {body}");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static void AppendRead(StringBuilder builder, string typeName, string name, string expression, int size)
    {
        builder.AppendLine($"    private static {typeName} {name}(global::System.ReadOnlySpan<byte> data, ref int offset)");
        builder.AppendLine("    {");
        builder.AppendLine($"        if (data.Length - offset < {size})");
        builder.AppendLine("            throw new global::System.InvalidOperationException(\"Truncated character wire.\");");
        builder.AppendLine($"        {typeName} value = {expression};");
        builder.AppendLine($"        offset += {size};");
        builder.AppendLine("        return value;");
        builder.AppendLine("    }");
        builder.AppendLine();
    }

    private static string Sanitize(string metadataName)
    {
        var builder = new StringBuilder(metadataName.Length);
        foreach (char character in metadataName)
            builder.Append(char.IsLetterOrDigit(character) ? character : '_');

        return builder.ToString();
    }
